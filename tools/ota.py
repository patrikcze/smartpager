#!/usr/bin/env python3
"""Signed OTA firmware tooling (needs only Python 3 and the `openssl` CLI).

  tools/ota.py keygen                 create secrets/ota_signing_key.pem (private, mode 600) and
                                      firmware/include/ota_pubkey.h (public key compiled into firmware)
  tools/ota.py sign BIN OUTDIR        write OUTDIR/firmware.bin + OUTDIR/manifest.json, signed

The private key never leaves this computer and is never uploaded to the server: the server
only hosts the signed image. Back the key up somewhere safe: without it you can't publish
updates for pagers built with its public key (they can still be reflashed over USB).
The version is taken from SMARTPAGER_VERSION in firmware/src/app_state.h.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KEY = ROOT / "secrets" / "ota_signing_key.pem"
PUB_HEADER = ROOT / "firmware" / "include" / "ota_pubkey.h"
VERSION_FILE = ROOT / "firmware" / "src" / "app_state.h"


def openssl(*args: str, data: bytes | None = None) -> bytes:
    return subprocess.run(["openssl", *args], input=data, capture_output=True, check=True).stdout


def public_pem() -> str:
    return openssl("ec", "-in", str(KEY), "-pubout").decode()


def write_header(pub: str) -> None:
    lines = "".join(f'    "{line}\\n" \\\n' for line in pub.strip().splitlines())
    PUB_HEADER.write_text(
        "// Generated by tools/ota.py keygen — public half of the OTA signing key (not secret).\n"
        "// Git-ignored so each owner builds firmware that trusts only their own key.\n"
        "#pragma once\n\n"
        "#define SMARTPAGER_OTA_PUBKEY \\\n" + lines + '    ""\n'
    )


def keygen(_: argparse.Namespace) -> int:
    if KEY.exists():
        print(f"{KEY.relative_to(ROOT)} already exists; refusing to overwrite (it signs your updates).")
        if not PUB_HEADER.exists():
            write_header(public_pem())
            print(f"recreated {PUB_HEADER.relative_to(ROOT)}")
        return 0
    KEY.parent.mkdir(mode=0o700, exist_ok=True)
    old = os.umask(0o077)
    try:
        KEY.write_bytes(openssl("ecparam", "-name", "prime256v1", "-genkey", "-noout"))
    finally:
        os.umask(old)
    os.chmod(KEY, 0o600)
    write_header(public_pem())
    print(f"private key: {KEY.relative_to(ROOT)}  (mode 600, git-ignored — back it up!)")
    print(f"public key:  {PUB_HEADER.relative_to(ROOT)}  (compiled into the firmware)")
    return 0


def current_version() -> str:
    m = re.search(r'#define SMARTPAGER_VERSION "(\d+\.\d+\.\d+)"', VERSION_FILE.read_text())
    if not m:
        sys.exit("SMARTPAGER_VERSION not found in firmware/src/app_state.h")
    return m.group(1)


def sign(args: argparse.Namespace) -> int:
    if not KEY.exists():
        sys.exit("no signing key — run: tools/ota.py keygen")
    image = Path(args.bin).read_bytes()
    if not image or image[0] != 0xE9:
        sys.exit(f"{args.bin} is not an ESP32 application image")
    version = args.version or current_version()
    digest = hashlib.sha256(image).hexdigest()
    message = f"smartpager-ota|{version}|{len(image)}|{digest}".encode()
    with tempfile.TemporaryDirectory() as tmp:
        msg = Path(tmp) / "msg"
        sig = Path(tmp) / "sig"
        pub = Path(tmp) / "pub.pem"
        msg.write_bytes(message)
        openssl("dgst", "-sha256", "-sign", str(KEY), "-out", str(sig), str(msg))
        pub.write_text(public_pem())
        openssl("dgst", "-sha256", "-verify", str(pub), "-signature", str(sig), str(msg))  # self-check
        signature = base64.b64encode(sig.read_bytes()).decode()
    out = Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(args.bin, out / "firmware.bin")
    manifest = {"version": version, "size": len(image), "sha256": digest, "signature": signature}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"signed {version}: {len(image)} bytes, sha256 {digest[:16]}… -> {out}")
    return 0


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("keygen").set_defaults(fn=keygen)
    s = sub.add_parser("sign")
    s.add_argument("bin")
    s.add_argument("outdir")
    s.add_argument("--version", help="override the version (default: from app_state.h)")
    s.set_defaults(fn=sign)
    args = p.parse_args()
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
